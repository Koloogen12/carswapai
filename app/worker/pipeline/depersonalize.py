"""
Обезличивание кадра перед отправкой во внешнюю модель.

ЗАЧЕМ. Класс B идёт в Gemini через прокси (OpenRouter или CometAPI). Прокси
решает доступность из РФ, но не законность: фотография всё равно уезжает за
границу, и получателей теперь двое. По 152-ФЗ ст. 12 это трансграничная
передача персональных данных в страну без адекватной защиты — под отдельное
письменное согласие на каждый снимок.

Обойти это можно единственным честным способом: сделать так, чтобы в
уезжающем кадре персональных данных НЕ БЫЛО. Тогда передавать нечего.

ЧТО ДЕЛАЕТ КАДР ПЕРСОНАЛЬНЫМИ ДАННЫМИ:
  · госномер — прямо идентифицирует владельца через базу ГИБДД;
  · фон — таблички домов, номера соседних машин, прохожие, витрины;
  · лица, в том числе отражённые в кузове и стёклах.

Связь с именем и телефоном остаётся у нас в базе и никуда не уезжает.

ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ. Он не даёт гарантии. VIN на лобовом стекле,
редкая машина, приметная оклейка — всё это опознаваемо и остаётся. Поэтому
решение «этого достаточно» принимает юрист, а не код. Наше дело — убрать
то, что убрать можно, и честно перечислить, что осталось.
"""
from __future__ import annotations

from dataclasses import dataclass

import cv2
import numpy as np


@dataclass(frozen=True)
class Outgoing:
    """Кадр, готовый к отправке наружу, и всё нужное, чтобы собрать обратно."""
    image: np.ndarray            # обрезанный и очищенный кадр
    mask: np.ndarray             # маска операции в координатах обрезки
    box: tuple[int, int, int, int]   # x, y, w, h в координатах оригинала
    removed: tuple[str, ...]     # что вырезано — для журнала и для юриста
    residual_risk: tuple[str, ...]   # что осталось и не убирается


def prepare(img: np.ndarray, car: np.ndarray, work: np.ndarray,
            plate: np.ndarray | None = None,
            margin: float = 0.06) -> Outgoing:
    """
    Обрезать по машине и вычистить всё опознаваемое.

    Обрезка — не оптимизация трафика, а мера защиты: за габаритом машины
    находится ровно то, что привязывает снимок к месту и к людям.
    """
    ys, xs = np.nonzero(car > 0)
    if len(xs) == 0:
        raise ValueError('машина в кадре не найдена — отправлять нечего')

    h, w = img.shape[:2]
    pad_x = int((xs.max() - xs.min()) * margin)
    pad_y = int((ys.max() - ys.min()) * margin)
    x0 = max(int(xs.min()) - pad_x, 0); x1 = min(int(xs.max()) + pad_x, w - 1)
    y0 = max(int(ys.min()) - pad_y, 0); y1 = min(int(ys.max()) + pad_y, h - 1)

    out = img[y0:y1 + 1, x0:x1 + 1].copy()
    car_c = car[y0:y1 + 1, x0:x1 + 1]
    work_c = work[y0:y1 + 1, x0:x1 + 1].copy()

    removed = ['фон за габаритом машины']

    # Госномер: заливаем нейтральным серым, а не размываем. Размытие обратимо
    # при должном старании, заливка — нет.
    if plate is not None and (plate > 0).any():
        pl = plate[y0:y1 + 1, x0:x1 + 1]
        out[pl > 0] = (128, 128, 128)
        work_c[pl > 0] = 0
        removed.append('госномер (залит, не размыт: размытие обратимо)')

    # Остатки фона внутри габарита — между колёсами, над капотом. Модель
    # всё равно перерисует только машину, а нам этот фон отдавать незачем.
    outside = (car_c == 0)
    if outside.any():
        out[outside] = (128, 128, 128)
        removed.append('фон внутри габарита')

    residual = []
    if plate is None or not (plate > 0).any():
        residual.append('ГОСНОМЕР НЕ НАЙДЕН И НЕ УДАЛЁН — отправлять нельзя')
    residual.append('VIN на лобовом стекле, если он в кадре')
    residual.append('отражения в кузове и стёклах')
    residual.append('приметная машина опознаваема сама по себе')

    return Outgoing(out, work_c, (x0, y0, x1 - x0 + 1, y1 - y0 + 1),
                    tuple(removed), tuple(residual))


def safe_to_send(o: Outgoing) -> tuple[bool, str | None]:
    """
    Можно ли это отправлять наружу.

    Отказ по умолчанию: если номер не найден, мы не знаем, где он, и значит
    не можем утверждать, что его нет в кадре. Отправить и надеяться — это то
    самое решение, из-за которого потом объясняются с Роскомнадзором.
    """
    for r in o.residual_risk:
        if r.startswith('ГОСНОМЕР НЕ НАЙДЕН'):
            # Код в начале строки — для экрана, текст после — для журнала.
            # Экран не должен показывать клиенту «трансграничная передача
            # персональных данных»: это верно по сути и бесполезно как совет.
            return False, ('plate_not_found: госномер не найден, отправка наружу '
                           'без этого — трансграничная передача персональных данных')
    return True, None


def restore(original: np.ndarray, edited_crop: np.ndarray,
            box: tuple[int, int, int, int]) -> np.ndarray:
    """Вернуть обработанную обрезку на место в полном кадре."""
    x, y, w, h = box
    out = original.copy()
    if edited_crop.shape[:2] != (h, w):
        edited_crop = cv2.resize(edited_crop, (w, h), interpolation=cv2.INTER_LANCZOS4)
    out[y:y + h, x:x + w] = edited_crop
    return out
