-- CarSwap AI · потолки расхода под новую экономику примерки
--
-- ПОЧЕМУ МЕНЯЕМ. Прежние 900/1800 ₽ посчитаны для карточки из трёх артикулов
-- сразу: 9 генераций по 8,5 ₽ = 76,5 ₽ за отправку. От этой модели
-- отказались — клиент примеряет по одному, и примерка стоит 3 генерации,
-- то есть 25,5 ₽.
--
-- Новый расчёт от той же цели §15 (90 примерок в месяц на точку):
--   90 × 25,5 ₽ = 2 295 ₽ переменных.
-- Мягкий порог ставим на 2 000 ₽ — предупреждение приходит ДО того, как
-- точка упрётся, а не вместе с остановкой. Жёсткий на 3 000 ₽: запас на
-- всплеск, но не бесконечный.
--
-- Старые значения останавливали точку на 71-й примерке из 90 запланированных.
-- То есть потолок, задуманный как страховка от разгона расхода, на деле
-- ломал бы нормальную работу — и первым это заметил бы не мониторинг,
-- а менеджер, у которого перестала нажиматься кнопка.
--
-- ЧЕГО ЗДЕСЬ НЕТ: правки уже посчитанных месяцев. Строки point_budgets
-- хранят предел, действовавший в своём месяце, и переписывать их задним
-- числом нельзя — иначе прошлые счета перестанут сходиться.

begin;

alter table points alter column soft_cap_kopecks set default 200000;   -- 2 000 ₽
alter table points alter column hard_cap_kopecks set default 300000;   -- 3 000 ₽

comment on column points.soft_cap_kopecks is
  '2 000 ₽ — предупреждение. 90 примерок по 25,5 ₽ дают 2 295 ₽, порог '
  'срабатывает раньше, чем точка упрётся.';
comment on column points.hard_cap_kopecks is
  '3 000 ₽ — остановка класса B. Класс A продолжает работать (§8.5), '
  'снятие стопа — на стороне сети (С-5).';

-- Точкам, у которых предел остался старым по умолчанию, поднимаем.
-- Тем, кому сеть выставила свой, не трогаем: это осознанное решение сети.
update points
   set soft_cap_kopecks = 200000, hard_cap_kopecks = 300000
 where soft_cap_kopecks = 90000 and hard_cap_kopecks = 180000;

commit;
