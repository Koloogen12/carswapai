-- CarSwap AI · заявка с лендинга
--
-- ЧТО ЗАКРЫВАЕТ. На лендинге не было ни одной формы и ни одного текстового
-- поля. Кнопка «Записаться на демо» в шапке вела на якорь #demo, а кнопка
-- внутри блока #demo — сама на себя. Посетитель, готовый купить, не мог
-- сообщить о себе ничего. Это первое звено сценария продаж: реклама →
-- лендинг → заявка → оплата → выдача доступа, и оно было разорвано.
--
-- ─────────────────────────────────────────────────────────────
-- ПОЧЕМУ ЗАЯВКА ВНЕ АРЕНДАТОРОВ И ЧЕМ ЭТО БЕЗОПАСНО
-- ─────────────────────────────────────────────────────────────
--
-- Заявка приходит снаружи, ДО всякой точки. Человек, который её оставляет,
-- ещё не арендатор: точки у него в системе нет, сети нет, пользователя нет.
-- Привязать заявку к точке было бы враньём — привязывать не к чему, а
-- выдуманная точка-«входящие» дала бы её владельцу законный доступ к чужим
-- телефонам. Поэтому у leads нет point_id, и это осознанный выбор, а не
-- пропуск.
--
-- Тогда возникает вопрос, на который отвечает вся эта миграция: если у
-- строки нет арендатора, на что опереться политике RLS?
--
-- Так уже стояли auth_codes и sessions в 014: они тоже нужны ДО того, как
-- арендатор известен, и там таблицы были выведены из-под RLS, а закрыты
-- жёстче — правами. Здесь тот же ответ, но развёрнутый на две стены,
-- а не на одну, и вот почему обе нужны:
--
--   СТЕНА 1 · RLS с force и ЕДИНСТВЕННОЙ политикой — для владельца схемы.
--     Владелец здесь не «привилегированный», а адрес: под ним и только под
--     ним исполняется тело security definer-функции приёма. Роль приложения
--     членом владельца не состоит и стать им не может, поэтому политика для
--     неё не применяется никогда — и select из leads под любой претензией
--     возвращает пусто. Это та же стена, что держит изоляцию всех остальных
--     таблиц, только предельная: не «свои строки», а ни одной.
--
--   СТЕНА 2 · права. `revoke all` ниже снимает с роли приложения право
--     писать: insert, update и delete отказываются ещё до политик. Читать
--     право возвращается, и почему именно так — объяснено там же, у revoke.
--     Записи же остаётся ровно один путь — функция приёма.
--
-- Ровно по этой причине здесь НЕ повторён приём 014 «вывести из-под RLS».
-- Таблица вне RLS выпадает из сплошного обхода в tests/client-link.sql —
-- единственной проверки, которая ловит утечку новой таблицы, не спрашивая
-- ничьей памяти. Заявка содержит телефон живого человека; уводить её из-под
-- надзора ради простоты нельзя.
--
-- Итог для проверки «заявка одной точки не видна другой»: она не видна
-- НИ ОДНОЙ точке. Это строго сильнее изоляции по point_id, и стенд
-- доказывает это и точке А, и точке Б.
--
-- Чтения заявок из приложения здесь нет намеренно: экрана «входящие заявки»
-- в продукте пока не существует, а функция чтения без экрана — это только
-- дыра, которую некому заметить. Появится экран — появится узкая функция
-- под него, с ролью и правами, а не общий select.
--
-- ─────────────────────────────────────────────────────────────
-- СОГЛАСИЕ И СРОК ХРАНЕНИЯ
-- ─────────────────────────────────────────────────────────────
--
-- Заявка — это имя и телефон человека, то есть персональные данные, и
-- основание для них нужно такое же, как для фотографии в гараже (§13).
-- Галочка на лендинге не отмечена по умолчанию — иначе это не согласие,
-- а оформление, — но одной галочки в интерфейсе мало: интерфейс меняется
-- чаще схемы. Поэтому основание выражено ограничением: строка без
-- согласия физически не существует (constraint leads_consent_required).
-- Функция приёма его НЕ перепроверяет заранее и не подменяет своей
-- вежливой ошибкой — иначе стенд доказывал бы аккуратность функции,
-- а не невозможность записи.
--
-- Срок хранения задаётся при записи, как у photos.retain_until в 001, а не
-- «когда-нибудь настроим». Год — тот же срок, что объявлен человеку на
-- экране согласия в гараже; для заявки он считается от её подачи.
-- Исполнитель срока — app.expire_leads() ниже. Заявка, в отличие от
-- клиента из 007, обезличиванию не подлежит: за ней нет ни наряда, ни
-- счёта, ни гарантии — учётного скелета, ради которого строку оставляют
-- жить, здесь просто нет. Значит строка удаляется целиком.
--
-- ЧЕСТНЫЙ ОСТАТОК: deploy/retention.sh сейчас вызывает только
-- app.expire_personal_data и про app.expire_leads не знает. Это одна
-- строка в скрипте вне территории этой задачи, и она записана здесь,
-- чтобы не потеряться: объявленный и неисполняемый срок хуже отсутствующего.
--
-- ─────────────────────────────────────────────────────────────
-- ПОВТОРНАЯ ОТПРАВКА
-- ─────────────────────────────────────────────────────────────
--
-- Две одинаковые заявки подряд — это один человек, дважды нажавший кнопку,
-- а не два клиента. Защита стоит в базе, а не в кнопке: кнопку можно
-- нажать из другой вкладки, с телефона и после перезагрузки страницы.
--
-- Ключ повтора — нормализованный телефон, и только он. Один человек — один
-- телефон: «+7 916…», «8 916…» и «79161112233» это он же. Название точки в
-- ключ НЕ входит намеренно — иначе опечатка в названии («Гараж 7» вместо
-- «Гараж №7») заводила бы вторую заявку на того же человека, а звонить ему
-- всё равно будут один раз. Двое с одной точки — владелец и управляющий —
-- разъедутся по разным телефонам, как и должны.
--
-- Ключ ВЫЧИСЛЯЕМЫЙ (generated always), а не переданный: вызывающий не может
-- его ни подделать, ни забыть. Считается он только из цифр, поэтому не
-- зависит от локали сервера — в отличие от любой попытки сравнивать
-- названия через lower(), которая на кластере с locale=C кириллицу не
-- сворачивает и тихо разъезжается между окружениями.
--
-- Уникальность частичная — только среди необработанных (status = 'new').
-- Так повтор в течение одной попытки невозможен, а человек, которому
-- перезвонили полгода назад и который пришёл снова, заявку оставить может.
-- Вечная уникальность по телефону закрыла бы ему дорогу навсегда.

begin;

create type lead_status as enum ('new', 'contacted', 'archived');

create table leads (
  id            uuid primary key default gen_random_uuid(),
  name          text not null,
  phone         text not null,
  point_name    text not null,
  source        text not null default 'landing',
  status        lead_status not null default 'new',

  -- Основание обработки. Версия документа — какую редакцию текста человек
  -- видел: без неё в споре нечего предъявить, ровно как в consents из 003.
  consent_granted           boolean not null,
  consent_document_version  text not null,
  consent_at                timestamptz not null default now(),
  ip                        inet,
  user_agent                text,

  -- §13: срок хранения задаётся при записи, а не «когда-нибудь настроим».
  retain_until  timestamptz not null default now() + interval '12 months',
  created_at    timestamptz not null default now(),

  -- Нет согласия — нет строки. Ограничение, а не проверка в коде: код
  -- переписывают чаще схемы.
  constraint leads_consent_required check (consent_granted),
  constraint leads_name_sane        check (length(btrim(name)) between 2 and 120),
  constraint leads_point_sane       check (length(btrim(point_name)) between 2 and 200)
);

-- Ключ повтора вычисляемый: app.normalize_phone из 015 объявлена immutable,
-- поэтому годится в generated-выражение.
alter table leads
  add column phone_normal text
    generated always as (app.normalize_phone(phone)) stored;

-- Телефон, который не телефон, — это заявка, по которой некому позвонить.
alter table leads
  add constraint leads_phone_sane check (phone_normal ~ '^\d{10,15}$');

-- Повтор невозможен, пока по заявке не поработали.
create unique index leads_dedupe_open on leads (phone_normal) where status = 'new';
-- Тот же индекс, что у photos: срок хранения ищется по нему.
create index leads_retention on leads (retain_until);

-- ── Стена 1 · RLS ──────────────────────────────────────────
alter table leads enable row level security;
alter table leads force row level security;

-- Единственная политика — по РОЛИ, а не по претензии: претензии у
-- посетителя лендинга нет и быть не может.
--
-- Адресат — владелец схемы, под которым исполняется тело security
-- definer-функции приёма. force row level security действует и на
-- владельца (об это уже спотыкалась очередь в 010), поэтому без этой
-- политики функция приёма молча вставляла бы ноль строк.
--
-- Имя роли берётся из current_user, а не пишется буквой: миграции всегда
-- едут от владельца схемы (см. migrate.sh), и так политика не разъедется
-- с окружением, где владельца зовут иначе.
--
-- Соблазн был опереть политику на метку вроде current_setting('app.lead'),
-- которую ставит сама функция. Отвергнут: такую метку может выставить кто
-- угодно, включая роль приложения, — политика стала бы декоративной.
-- Роль подделать нельзя: app_tenant не член владельца и стать им не может.
do $$
begin
  execute format(
    'create policy leads_intake on leads as permissive for all to %I '
    'using (true) with check (true)', current_user);
end $$;

-- ── Стена 2 · права ────────────────────────────────────────
-- 005 раздаёт арендатору select/insert/update/delete на все будущие
-- таблицы через alter default privileges. Для заявки право писать — лишнее:
-- единственный законный путь записи — функция приёма ниже.
revoke all on table leads from app_tenant, public;

-- Право ЧИТАТЬ возвращается сознательно, и вот зачем. Прогон
-- tests/client-link.sql делает сплошной обход всех таблиц под RLS и требует
-- от каждой ноль строк — так ловится таблица, заведённая новой миграцией и
-- забытая в перечнях. Таблица, к которой нет доступа вовсе, из этого обхода
-- выпадает: она не «отдаёт ноль», она роняет проверку. Отзыв select спрятал
-- бы leads от единственного стенда, который следит за утечками, — и следующая
-- таблица рядом с ней уехала бы в бой непроверенной.
--
-- Читать при этом всё равно нечего: политика адресована владельцу схемы,
-- к роли приложения она не применяется, и select под любой претензией
-- возвращает пусто. Право есть — строк нет.
grant select on table leads to app_tenant;

-- ── Приём заявки ───────────────────────────────────────────
-- Возвращает идентификатор заявки, признак «создана впервые» и срок
-- хранения. Срок отдаётся наружу не для красоты: без него ни стенд, ни
-- человек не могут убедиться, что он вообще проставлен, — а прочитать
-- строку из leads нельзя ни тому, ни другому.
create or replace function app.submit_lead(
  p_name        text,
  p_phone       text,
  p_point_name  text,
  p_consent     boolean,
  p_doc_version text,
  p_ip          inet default null,
  p_user_agent  text default null
) returns table (lead_id uuid, was_created boolean, keep_until timestamptz)
language plpgsql security definer set search_path = public, app, pg_temp as $$
declare
  k   text := app.normalize_phone(p_phone);
  rec leads;
begin
  -- Сначала ищем уже лежащую необработанную заявку: повтор — это норма
  -- (дрогнула рука), а не исключительная ситуация.
  select * into rec from leads where leads.phone_normal = k and leads.status = 'new';
  if rec.id is not null then
    return query select rec.id, false, rec.retain_until;
    return;
  end if;

  begin
    insert into leads (name, phone, point_name, consent_granted,
                       consent_document_version, ip, user_agent)
    values (btrim(p_name), btrim(p_phone), btrim(p_point_name), p_consent,
            p_doc_version, p_ip, p_user_agent)
    returning * into rec;
  exception when unique_violation then
    -- Два нажатия в один и тот же миг: первая транзакция закоммитилась
    -- между нашим select и insert. Уникальный индекс — та самая вторая
    -- стена, ради которой он частичный, а не «проверим и вставим».
    select * into rec from leads where leads.phone_normal = k and leads.status = 'new';
    return query select rec.id, false, rec.retain_until;
    return;
  end;

  return query select rec.id, true, rec.retain_until;
end $$;

-- ── Отметка о работе с заявкой ─────────────────────────────
-- Без неё status был бы колонкой, которую никто не может изменить, а
-- частичная уникальность «только среди new» — обещанием, которое некому
-- исполнить: человек, оставивший заявку однажды, не смог бы прийти снова
-- никогда.
--
-- Функция ничего о заявке НЕ рассказывает: она не возвращает ни телефона,
-- ни имени, ни даже факта существования строки сверх числа изменённых.
-- Это не путь чтения, и им она не станет.
--
-- ARCHIVED МЕНЯЕТ СРОК ХРАНЕНИЯ, и это не мелочь. «В архив» означает, что
-- по заявке решили не работать: цель обработки достигнута (точнее, оставлена),
-- а по 152-ФЗ ст. 5 ч. 7 данные уничтожаются ПО достижении цели, а не через
-- год после неё. Держать телефон человека, которому мы уже решили не
-- звонить, оснований нет.
create or replace function app.mark_lead(p_lead uuid, p_status lead_status)
returns boolean language plpgsql security definer
set search_path = public, app, pg_temp as $$
declare n integer;
begin
  update leads
     set status = p_status,
         retain_until = case when p_status = 'archived' then now() else retain_until end
   where id = p_lead and status is distinct from p_status;
  get diagnostics n = row_count;
  return n > 0;
end $$;

-- ── Исполнение срока хранения ──────────────────────────────
-- Заявка удаляется целиком: обезличивать в ней нечего — без имени и
-- телефона от неё не остаётся ничего, на что мог бы сослаться учёт.
-- Возвращает число удалённых, чтобы вызывающий крутил порциями до нуля,
-- как это делает retention.sh с app.expire_personal_data.
create or replace function app.expire_leads(batch integer default 200)
returns integer language plpgsql security definer
set search_path = public, app, pg_temp as $$
declare n integer;
begin
  with due as (
    select id from leads where retain_until <= now()
     order by retain_until limit batch for update skip locked
  )
  delete from leads l using due where l.id = due.id;
  get diagnostics n = row_count;
  return n;
end $$;

revoke all on function app.submit_lead(text, text, text, boolean, text, inet, text)
  from public;
revoke all on function app.expire_leads(integer) from public;
revoke all on function app.mark_lead(uuid, lead_status) from public;
grant execute on function app.submit_lead(text, text, text, boolean, text, inet, text)
  to app_tenant;
grant execute on function app.expire_leads(integer) to app_tenant;
grant execute on function app.mark_lead(uuid, lead_status) to app_tenant;

commit;
