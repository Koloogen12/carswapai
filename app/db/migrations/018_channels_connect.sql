-- CarSwap AI · миграция 018 · подключение каналов точки
--
-- ЧТО ЗАКРЫВАЕТ. Каналы существовали только в посевных данных. Завести их
-- было нечем: экрана нет, серверных действий нет, и четвёртый шаг запуска
-- точки («подключает аккаунты соцсетей») физически не выполнялся. Без него
-- в продукт не приходит ни одного обращения, то есть точку нельзя запустить.
--
-- Но дописать экран мало. Под ним в схеме лежали три дыры.
--
--   1. Уникальность канала была В ПРЕДЕЛАХ ТОЧКИ: unique (point_id, kind,
--      external_id). То есть один и тот же внешний идентификатор — GUID
--      канала Wazzup или идентификатор аккаунта Авито — можно было привязать
--      к двум точкам сразу. Резолвер из 009 ищет по (provider, external_id,
--      kind) с limit 1 и берёт первую попавшуюся строку: обращения чужого
--      бизнеса поехали бы в чужой инбокс. Молча, потому что «нашлась не та
--      строка» — не ошибка.
--
--   2. Каналы МЕНЯЛ КТО УГОДНО из точки. Политика channels_tenant из 001
--      пускает на запись любого, у кого претензия этой точки, — то есть
--      менеджера и мастера. Менеджер мог отключить канал точки или завести
--      свой и увести поток обращений. Проверка «только владелец» в коде
--      приложения от этого не спасает: запрос мимо приложения её не видит.
--
--   3. Возможностям канала неоткуда было взяться честно. capabilities()
--      у Wazzup зависит от транспорта — WhatsApp Business API писать первым
--      не может, личный номер может, Telegram-бот не может, — а в схеме
--      транспорт не хранился вовсе. can_initiate заполнялся руками, то есть
--      мог разойтись с тем, что канал умеет на самом деле. Разошедшийся
--      флаг хуже отсутствующего: менеджер узнаёт про запрет не от нас,
--      а от молчащего клиента.
--
-- ЧЕГО ЗДЕСЬ СОЗНАТЕЛЬНО НЕТ: колонки под ключ шлюза. Ключи живут в
-- переменных окружения (см. src/lib/adapters/impl/transport.ts) и в базу не
-- попадают ни при каком сценарии. credentials_ref — это ИМЯ переменной,
-- а не её значение, и ниже это закреплено ограничением, а не договорённостью.

begin;

-- ─────────────────────────────────────────────────────────────
-- 1. Один внешний идентификатор — одна точка. Глобально.
-- ─────────────────────────────────────────────────────────────
--
-- Индекс, а не триггер и не проверка в коде. Причина ровно одна: RLS
-- действует и на тело триггера, и на security definer (carswap_owner создан
-- nobypassrls), поэтому проверить «а нет ли такого канала у ЧУЖОЙ точки»
-- запросом нельзя — чужие строки не видны по построению. Уникальный индекс
-- работает ниже RLS и видит всю таблицу; другого механизма здесь нет.
--
-- Побочный эффект известен и принят: точка Б, попытавшись привязать канал
-- точки А, получит отказ и узнает, что такой канал где-то уже заведён.
-- Это ровно то, что ей и надо сообщить, — а альтернатива (молча увести
-- чужие обращения) несопоставимо хуже.
--
-- Пара (provider, external_id) без kind: у Wazzup идентификатор канала
-- уникален сам по себе, у Авито это аккаунт продавца. Добавь сюда kind —
-- и один GUID можно было бы завести дважды, как whatsapp и как telegram.
create unique index channels_provider_external on channels (provider, external_id);

-- ─────────────────────────────────────────────────────────────
-- 2. Транспорт канала и результат проверки связи
-- ─────────────────────────────────────────────────────────────

-- От транспорта зависит право писать первым, и только от него. Значение
-- берётся из того же словаря, что и WazzupConfig.transport, — иначе
-- capabilities() и база разойдутся.
alter table channels add column transport text
  check (transport is null or transport in ('business_api','personal','bot'));

-- Что именно сломалось и что нажать. health() адаптера возвращает и то и
-- другое; last_error без подсказки — это «не работает» без причины, ради
-- которого точка и звонит в управляющую компанию.
alter table channels add column fix_hint text;

-- Когда шлюз спрашивали в последний раз. Без отметки экран не отличает
-- «проверено минуту назад и всё хорошо» от «не проверялось ни разу».
alter table channels add column checked_at timestamptz;

-- Транспорт посевных каналов восстанавливаем из can_initiate, а не ставим
-- наугад: строки уже показаны на экранах, и менять их смысл нельзя.
--   whatsapp + пишет первым  → личный номер;
--   whatsapp не пишет первым → Business API (шаблоны вне окна);
--   telegram + пишет первым  → личный аккаунт;
--   telegram не пишет первым → бот.
update channels
   set transport = case
     when can_initiate then 'personal'
     when kind = 'whatsapp' then 'business_api'
     else 'bot'
   end
 where kind in ('whatsapp','telegram');

-- ─────────────────────────────────────────────────────────────
-- 3. Секрет в базе не окажется по построению
-- ─────────────────────────────────────────────────────────────
--
-- В колонке лежит ИМЯ переменной окружения (WAZZUP_API_KEY), а не ключ.
-- Форма имени выбрана так, что настоящий ключ в неё не влезает: ключи шлюзов
-- содержат строчные буквы, дефисы и точки, а здесь их нет. Это не догадка про
-- формат ключей, а нарочно узкий коридор: ошибиться и записать значение
-- вместо имени становится невозможно, а не маловероятно.
alter table channels add constraint channels_credentials_ref_is_env_name
  check (credentials_ref is null or credentials_ref ~ '^[A-Z][A-Z0-9_]{2,63}$');

-- ─────────────────────────────────────────────────────────────
-- 4. Подключает и отключает только владелец
-- ─────────────────────────────────────────────────────────────
--
-- Отдельной функцией, а не выражением в трёх политиках: одно правило в одном
-- месте. Разъехавшиеся копии условия — дыра, которую никто не заметит.
-- Тот же приём, что у app.staff_writable в 016.
-- ЗДЕСЬ НЕТ ОБРАЩЕНИЯ К points, И ЭТО НЕ ЭКОНОМИЯ. Проверка «точка из моей
-- сети» требует чтения points, а политика points_by_channel из 009 читает
-- channels, политика channels_tenant из 001 снова зовёт app.point_visible —
-- и получается взаимная рекурсия через границу security definer, которую
-- Postgres не распознаёт как рекурсию политик и роняет по глубине стека.
-- Проверено на стенде: попытка админа чужой сети завести канал падала
-- с «stack depth limit exceeded» вместо честного отказа.
--
-- Сеть проверять здесь и не нужно: разрешающая политика channels_tenant из
-- 001 уже сужает network_admin до точек своей сети (`with check
-- (app.point_visible(point_id))`), а ограничительная политика складывается
-- с ней по «и». Эта функция отвечает ровно на свой вопрос — КТО, а не ГДЕ.
create or replace function app.channel_writable(p_point uuid)
returns boolean language sql stable as $$
  select case app.current_role_name()
    -- Управляющая компания — да; в какой точке, решает channels_tenant.
    when 'network_admin' then true
    -- Владелец точки — только свою точку.
    when 'owner'         then p_point = app.current_point_id()
    -- Менеджер и мастер каналы не трогают. Никак.
    else false
  end
$$;

-- Политики отдельно на каждую команду, а не одна `for all`: `using` у
-- `for all` действует и на select, и тогда менеджер перестал бы видеть
-- состояние каналов в инбоксе и в сводке точки. Задача про запись —
-- ограничиваем запись.
create policy channels_insert_owner on channels as restrictive for insert
  with check (app.channel_writable(point_id));

create policy channels_update_owner on channels as restrictive for update
  using (app.channel_writable(point_id))
  with check (app.channel_writable(point_id));

create policy channels_delete_owner on channels as restrictive for delete
  using (app.channel_writable(point_id));

grant execute on function app.channel_writable(uuid) to app_tenant;

commit;
