'use server';
/**
 * Заявка с лендинга.
 *
 * Первое звено сценария продаж: реклама → лендинг → заявка → оплата →
 * выдача доступа. До миграции 017 звена не было вовсе: на «/» не было ни
 * одной формы, а кнопка «Записаться на демо» внутри блока #demo вела сама
 * на себя.
 *
 * ЧЕЙ ЭТО АРЕНДАТОР. Ничей. Человек, который оставляет заявку, ещё не точка
 * и не сеть: подключать его некуда, претензию выставить не из чего. Поэтому
 * здесь нет ни withTenant, ни withGarage — только узкая функция приёма
 * app.submit_lead, единственный путь записи в leads. Обоснование, почему это
 * безопасно, лежит в комментарии миграции 017, а не пересказывается тут.
 *
 * ПОЧЕМУ ВАЛИДАЦИЯ ЗДЕСЬ, ЕСЛИ ОНА ЕСТЬ В БАЗЕ. Не «на всякий случай»:
 * ограничения таблицы отвечают за то, чтобы мусор не лёг, а этот код — за
 * то, чтобы человек увидел причину отказа своими словами, а не сообщение
 * Postgres о нарушении leads_phone_sane. Стеной остаётся база: если эти
 * проверки разойдутся с ней, ляжет запись, а не мусор.
 *
 * СОГЛАСИЕ. Галочка на форме не отмечена по умолчанию, и это не украшение:
 * заявка — это имя и телефон живого человека, то есть персональные данные,
 * и основание для их обработки нужно ровно такое же, как для фотографии в
 * гараже (§13, src/lib/garage.ts). Что человек видел, фиксируется версией
 * документа ниже: меняется текст — меняется версия, иначе в споре нечего
 * предъявить.
 */
import { headers } from 'next/headers';
import { sys } from './db';

/* Редакция текста согласия под формой. Меняется текст — меняется версия.
 * Наружу не выносится: в файле с 'use server' экспортировать можно только
 * асинхронные функции, иначе сборка падает целиком — и падает она на всей
 * странице, а не на этом модуле. */
const CONSENT_VERSION = 'landing-2026-08-1';

export type LeadInput = {
  name: string;
  phone: string;
  pointName: string;
  consent: boolean;
};

export type LeadResult =
  /** `duplicate` — заявка уже лежала: человек нажал кнопку второй раз. */
  | { ok: true; duplicate: boolean }
  | { ok: false; error: string };

/** Только цифры. Один и тот же номер приходит как +7…, 8…, со скобками. */
function digits(raw: string): string {
  return raw.replace(/\D/g, '');
}

/**
 * Адрес отправителя. Пишется в заявку как след действия — тем же составом,
 * что и в consents из миграции 003 (ip, user_agent): без него согласие
 * нечем подтвердить.
 *
 * За обратным прокси настоящий адрес приходит в x-forwarded-for списком,
 * нужен первый. Всё, что не похоже на адрес, отбрасываем в null: в колонку
 * типа inet мусор не лезет, а ронять из-за него заявку — терять клиента.
 */
function callerIp(h: Headers): string | null {
  const raw = (h.get('x-forwarded-for') ?? h.get('x-real-ip') ?? '')
    .split(',')[0]
    .trim();
  if (!raw) return null;
  const looksLikeAddress = /^[0-9a-fA-F:.]+$/.test(raw) && raw.length <= 45;
  return looksLikeAddress ? raw : null;
}

/**
 * Принять заявку.
 *
 * Повтор не считается ошибкой и не показывается человеку как отказ: две
 * одинаковые заявки подряд — это один человек, дважды нажавший кнопку.
 * Различает их база (частичный уникальный индекс по нормализованному
 * телефону среди необработанных), а не эта функция: кнопку жмут и из
 * другой вкладки, и после перезагрузки страницы, и с телефона — там нет
 * никакого общего состояния, кроме базы.
 */
export async function submitLead(input: LeadInput): Promise<LeadResult> {
  const name = input.name.trim();
  const pointName = input.pointName.trim();
  const phone = input.phone.trim();
  const phoneDigits = digits(phone);

  if (!input.consent) {
    return {
      ok: false,
      error: 'Без согласия на обработку данных мы не можем сохранить заявку',
    };
  }
  if (name.length < 2 || name.length > 120) {
    return { ok: false, error: 'Напишите, как к вам обращаться' };
  }
  if (phoneDigits.length < 10 || phoneDigits.length > 15) {
    return { ok: false, error: 'Проверьте телефон — по этому номеру не дозвониться' };
  }
  if (pointName.length < 2 || pointName.length > 200) {
    return { ok: false, error: 'Напишите название точки — с ним разговор начнётся быстрее' };
  }

  const h = headers();
  const rows = await sys<{ was_created: boolean }>(
    `select was_created from app.submit_lead($1,$2,$3,$4,$5,$6::inet,$7)`,
    [name, phone, pointName, true, CONSENT_VERSION,
     callerIp(h), h.get('user-agent')],
  );

  // Пусто здесь означает, что функция приёма не вернула строку. Молчать
  // нельзя: снаружи это выглядело бы как принятая заявка, а человек ждал бы
  // звонка, которого никто не сделает.
  if (!rows.length) {
    return { ok: false, error: 'Заявка не сохранилась. Позвоните нам или попробуйте ещё раз' };
  }
  return { ok: true, duplicate: !rows[0].was_created };
}
