/**
 * Доменные константы, в которых живут инварианты.
 *
 * Лежат в lib, а не в компоненте: инвариант не должен зависеть от того,
 * какой экран его импортирует, и не должен исчезнуть вместе с вёрсткой.
 */

/** О-2 · три световых условия. Порядок фиксирован и задан здесь. */
export const LIGHTS = [
  { id: 'day', label: 'День' },
  { id: 'overcast', label: 'Пасмурно' },
  { id: 'parking', label: 'Паркинг' },
] as const;
export type LightId = typeof LIGHTS[number]['id'];

/** О-2 · строка честности. Одна на продукт, без вариантов и без тумблера. */
export const HONESTY_LINE =
  'Оттенок партии сверим с рулоном при вас на замере — образец приложим к записи.';

/**
 * Имя продукта — одним местом.
 *
 * До переименования в YOOMP оно было рассыпано по одиннадцати строкам в пяти
 * файлах: шапка кабинета, вход, лендинг, вкладка браузера. Переименование
 * такого рода всегда забывает одну строку, и продукт выходит в мир с двумя
 * именами сразу.
 *
 * Отсюда берутся ЯРЛЫКИ — шапка, вход, вкладка браузера. На лендинге имя
 * стоит в прозе («Чат рисует похожую машину. YOOMP перекрашивает его»), где
 * это слово предложения, а не подпись элемента, и подстановка переменной
 * читалась бы хуже текста.
 */
export const BRAND = 'YOOMP';

export type ChannelId = 'whatsapp' | 'telegram' | 'max' | 'avito' | 'web';

/**
 * Состояние строки инбокса.
 *
 * warranty — жалоба на уже сданную работу. Стоит в этом же перечне, хотя к
 * примерке отношения не имеет: у строки инбокса состояние одно, и «клиент
 * вернулся с проблемой» обязано вытеснять всё остальное, а не показываться
 * рядом с ним.
 */
export type TryonStateId =
  'warranty' | 'sent' | 'more' | 'confirmed' | 'booked' | 'undelivered' | 'channel_off';
