/**
 * Отказ примерки, переведённый человеку.
 *
 * ЧТО БЫЛО. `render_jobs.last_error` уходил на экран как есть, и клиент,
 * загрузивший кадр без видимого номера, читал: «госномер не найден: без этого
 * отправка наружу — трансграничная передача персональных данных». Фраза верная
 * по сути и бесполезная как совет: она не говорит, что делать, зато сообщает
 * постороннему человеку, что его снимок куда-то отправляют.
 *
 * КАК УСТРОЕНО. Воркер пишет в начале строки короткий КОД, дальше технический
 * текст. Код читает экран, текст остаётся в журнале и на учётных экранах —
 * тому, кто разбирает сбой, нужна причина, а не утешение.
 *
 * Разбор идёт по коду, а не по тексту: сопоставление с русской фразой
 * разъезжается на первой же правке формулировки в воркере, причём молча —
 * пользователь просто снова начинает видеть техническую строку.
 *
 * КЛИЕНТ И СОТРУДНИК СЛЫШАТ РАЗНОЕ, потому что могут разное. Клиент способен
 * переснять; менеджер — попросить. Одна формулировка на двоих оказалась бы
 * бесполезной хотя бы одному из них.
 */

/** Кому адресован текст: тому, кто может переснять, или тому, кто может попросить. */
export type Audience = 'client' | 'staff';

const SAYS: Record<string, Record<Audience, string>> = {
  plate_not_found: {
    client: 'Нужен кадр, где виден госномер. Мы закрываем его перед обработкой — '
          + 'на снимке, где номера не видно, сделать этого не можем.',
    staff:  'На кадре не виден госномер. Попросите фото спереди или в три четверти: '
          + 'номер закрывается до обработки, и без него примерка не идёт.',
  },
  no_car: {
    client: 'На кадре не нашли машину. Нужен один автомобиль целиком — сбоку или '
          + 'в три четверти.',
    staff:  'На кадре не нашлась машина. Нужен один автомобиль целиком, сбоку или '
          + 'в три четверти — крупный план детали не подойдёт.',
  },
  no_photo: {
    client: 'Кадр не открылся. Загрузите фотографию заново.',
    staff:  'Файл кадра не открылся — попросите прислать фотографию ещё раз.',
  },
  budget: {
    // Здесь человек не может сделать НИЧЕГО, и предлагать ему действие было бы
    // издевательством. Клиенту про деньги точки не говорим вовсе: это не его
    // дело и не его вина.
    client: 'Новые кадры на сегодня закончились. Готовые примерки открываются '
          + 'как обычно — они мгновенные.',
    staff:  'Исчерпан месячный потолок расхода точки. Снимает его сеть.',
  },
  qa: {
    client: 'Кадр не прошёл проверку. Попробуйте другой снимок — лучше при ровном '
          + 'свете и без бликов на кузове.',
    staff:  'Результат не прошёл контроль качества. Попросите другой кадр: ровный '
          + 'свет, без сильных бликов и отражений на кузове.',
  },
};

const FALLBACK: Record<Audience, string> = {
  client: 'Не получилось посчитать этот кадр. Попробуйте другой снимок.',
  staff:  'Кадр не посчитался. Причина записана в журнале задания.',
};

/**
 * Перевести причину отказа.
 *
 * Незнакомый код — общая фраза, а не показ технической строки: неизвестный код
 * означает, что воркер обогнал экран, и в этот момент пользователю нельзя
 * показывать внутренности. Причина при этом не теряется — она осталась в
 * задании и видна на учётных экранах.
 */
export function refusalText(raw: string | null | undefined,
                            who: Audience = 'client'): string {
  // Воркер записывает причину как «RuntimeError: plate_not_found: …» — имя
  // исключения перед кодом ставит он сам, и оно полезно в журнале. Поэтому
  // якорь на начало строки не годится: он ищет код там, где стоит класс
  // ошибки. Снимаем возможный префикс класса и читаем код за ним.
  const text = String(raw ?? '').replace(/^[A-Za-z]+(Error|Exception):\s*/, '');
  const code = text.match(/^([a-z_]{2,32}):/)?.[1];
  return (code && SAYS[code]?.[who]) || FALLBACK[who];
}

/** Убрать повторы: три света падают одной причиной, и говорить её трижды незачем. */
export function refusalTexts(raws: (string | null | undefined)[],
                             who: Audience = 'client'): string[] {
  return [...new Set(raws.map(r => refusalText(r, who)))];
}
