/**
 * Дательный падеж имени — «Ответить Наталье…», а не «Ответить Наталья…».
 *
 * Мелочь, которая стоит на каждом экране диалога и читается как небрежность:
 * в макете стояло «Ответить Ивану…», в коде подставлялся именительный.
 *
 * Правило намеренно неполное. Русское склонение имён — это исключения, и
 * попытка накрыть все даст «Отправить Любовье». Поэтому: узнали окончание —
 * склоняем, не узнали — оставляем как есть. Именительный падеж читается
 * шероховато, выдуманная форма читается как ошибка.
 */

/** Имена, которые не склоняются вовсе: чужие и русские на -о, -е, -и, -у. */
const INDECLINABLE = /(?:[оеиуыэюё]|ко)$/i;

/** Женские на -ь: Любовь → Любови, Нинель → Нинели. Мужские на -ь: Игорь → Игорю. */
const FEMININE_SOFT = /^(?:любовь|нинель|рахиль|адель|эсфирь)$/i;

export function dative(name: string): string {
  const n = name.trim();
  if (!n || !/^[а-яё-]+$/i.test(n)) return n;         // латиница и составное — не трогаем
  const low = n.toLowerCase();

  if (FEMININE_SOFT.test(low)) return n.slice(0, -1) + 'и';
  if (low.endsWith('ия')) return n.slice(0, -1) + 'и';   // Мария → Марии
  if (low.endsWith('ья')) return n.slice(0, -1) + 'е';   // Наталья → Наталье
  if (low.endsWith('я'))  return n.slice(0, -1) + 'е';   // Илья → Илье, Женя → Жене
  if (low.endsWith('а'))  return n.slice(0, -1) + 'е';   // Анна → Анне, Никита → Никите
  if (low.endsWith('й'))  return n.slice(0, -1) + 'ю';   // Дмитрий → Дмитрию
  if (low.endsWith('ь'))  return n.slice(0, -1) + 'ю';   // Игорь → Игорю
  if (INDECLINABLE.test(low)) return n;                  // Отто, Тимо, Дмитро
  if (/[бвгджзклмнпрстфхцчшщ]$/i.test(low)) return n + 'у'; // Иван → Ивану
  return n;
}
