import type { MetadataRoute } from 'next';

/**
 * Что можно индексировать.
 *
 * Лендинг — можно и нужно: он для того и написан. Всё остальное — нельзя, и
 * не из осторожности: за ссылкой клиента стоит его сделка с именем, машиной и
 * суммой, за гаражом — прайс конкретной точки, за печатными формами — наряд с
 * госномером. Такие адреса не угадываются, но поисковик узнаёт их из
 * переходов и заголовка Referer, а дальше они попадают в выдачу.
 *
 * Список закрытого перечисляется явно, а не «всё кроме корня»: правило
 * Disallow: / с исключением Allow: / читается разными роботами по-разному, и
 * ошибка в такую сторону стоит утечки, а не потери трафика.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: [{
      userAgent: '*',
      allow: '/',
      disallow: [
        '/inbox', '/crm', '/price', '/staff', '/channels', '/network',
        '/bay', '/owner', '/ops', '/measure', '/join', '/login',
        '/g/',    // гараж точки: прайс и остатки
        '/c/',    // ссылка клиента: его сделка целиком
        '/doc/',  // печатные формы: наряд, счёт, гарантийный талон
        '/api/',
        '/dev-states', '/dev-port',
      ],
    }],
  };
}
